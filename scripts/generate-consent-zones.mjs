// Writes src/lib/consent-zones.generated.ts: the browser time zones of the ask-first countries in
// src/lib/consent-regions.ts. Run with `npm run consent-zones` after changing that list.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const regionsFile = fs.readFileSync(path.join(root, "src/lib/consent-regions.ts"), "utf8");
const codes = new Set(regionsFile.match(/CONSENT_REGIONS = "([A-Z ]+)"/)[1].split(" "));

const zones = new Set();
for (const line of fs.readFileSync("/usr/share/zoneinfo/zone.tab", "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [country, , zone] = line.split("\t");
  if (!codes.has(country)) continue;
  zones.add(zone);
  // Browsers report ICU's name, which is often the older one (Asia/Saigon for Asia/Ho_Chi_Minh).
  try {
    zones.add(new Intl.DateTimeFormat("en", { timeZone: zone }).resolvedOptions().timeZone);
  } catch {
    // A zone newer than this Node's ICU: the zone.tab name alone will have to do.
  }
}

// Europe/* is matched by its prefix, so it stays out of the list.
const list = [...zones].filter((z) => !z.startsWith("Europe/")).sort();
const out = [
  "// Generated by scripts/generate-consent-zones.mjs from /usr/share/zoneinfo/zone.tab. Do not edit by hand.",
  `export const ASK_FIRST_ZONES: readonly string[] = ${JSON.stringify(list, null, 2)};`,
  "",
].join("\n");
fs.writeFileSync(path.join(root, "src/lib/consent-zones.generated.ts"), out);
console.log(`Wrote ${list.length} time zones for ${codes.size} countries.`);
